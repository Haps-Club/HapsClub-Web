#!/usr/bin/env python3
"""Rewrite the <header> and <footer> of every page from scripts/site_chrome.py.

Idempotent: it matches whatever header/footer is there and replaces it with the
canonical one, so running it twice changes nothing the second time.

  python3 scripts/normalize_chrome.py            # write
  python3 scripts/normalize_chrome.py --check    # exit 1 if any page is stale

Scope: index.html plus every page that already uses the shared subpage shell
(header class="snav", "nav" or the old issue-page "bar"). The standalone one-offs under events/,
planner/, planner-svetlana/ and partnership/ have their own bespoke chrome and
are deliberately left alone.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import site_chrome as sc  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = ("events", "planner", "planner-svetlana", "partnership", ".git")

HEADER_RE = re.compile(r'<header class="(?:snav|nav|bar)"[^>]*>.*?</header>', re.S)
CHROME_RE = re.compile(r'[ \t]*<link[^>]+assets/(?:chrome(?:-f)?|pages-f)\.css[^>]*>\n?')
# chrome.css must load BEFORE the page stylesheet so page rules can still win.
# sunset-pages.css / pages-f.css are the pre-merge names of site.css.
PAGE_CSS_RE = re.compile(
    r'([ \t]*)<link[^>]+assets/(?:site|sunset-pages)\.css(?:\?[^"\']*)?[^>]*>')
FIRST_CSS_RE = re.compile(r'^([ \t]*)<link[^>]+assets/[^"\']+\.css', re.M)
FOOTER_RE = re.compile(r'<footer[^>]*>.*?</footer>', re.S)
# Pages that opt in to the homepage's sponsor block carry this section.
SPONS_RE = re.compile(r'<section class="blk spons-wrap">.*?</section>', re.S)


def sponsor():
    with open(os.path.join(ROOT, "data", "events.json"), encoding="utf-8") as f:
        return json.load(f).get("sponsor")

# Which nav item to mark current, by path prefix. Longest match wins.
ACTIVE = [("ask/", "/ask/"), ("guides/", "/guides/"), ("archive/", "/archive/"),
          ("about.html", "/about"), ("subscribe.html", "/subscribe"),
          ("privacy.html", "/privacy"),
          ("index.html", "/#list")]


def active_for(rel):
    for prefix, href in ACTIVE:
        if rel.startswith(prefix) or rel == prefix:
            return href
    return ""


def ensure_chrome_link(src):
    """Link assets/chrome.css before the page's first stylesheet (partners.html
    loads partners.css ahead of site.css), and put a content hash on both so
    Cloudflare cannot serve either one stale."""
    src = CHROME_RE.sub("", src)
    m = PAGE_CSS_RE.search(src)
    if not m:
        return src
    src = src[:m.start()] + m.group(1) + sc.page_css() + src[m.end():]
    first = FIRST_CSS_RE.search(src)
    return src[:first.end(1)] + sc.chrome_css() + "\n" + first.group(1) + src[first.end(1):]


def pages():
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames
                       if d not in SKIP_DIRS and not d.startswith("_")]
        for fn in sorted(filenames):
            if fn.endswith(".html"):
                yield os.path.relpath(os.path.join(dirpath, fn), ROOT)


def main(check=False):
    stale, done = [], []
    for rel in pages():
        if rel == "index.html":
            continue  # generated by scripts/build_home.py, which calls site_chrome itself
        path = os.path.join(ROOT, rel)
        src = open(path, encoding="utf-8").read()
        if not HEADER_RE.search(src):
            continue                      # bespoke page, not ours
        new = ensure_chrome_link(src)
        new = HEADER_RE.sub(lambda m: sc.header(active=active_for(rel)),
                            new, count=1)
        if FOOTER_RE.search(new):
            new = FOOTER_RE.sub(lambda m: sc.footer(), new, count=1)
        if SPONS_RE.search(new):
            new = SPONS_RE.sub(lambda m: sc.sponsors(sponsor(), cls="blk spons-wrap"),
                               new, count=1)
        if new == src:
            continue
        stale.append(rel)
        if not check:
            open(path, "w", encoding="utf-8").write(new)
            done.append(rel)
    if check:
        if stale:
            print("stale chrome in %d page(s):" % len(stale))
            for r in stale:
                print("  " + r)
            return 1
        print("chrome up to date")
        return 0
    print("rewrote chrome on %d page(s)" % len(done))
    for r in done:
        print("  " + r)
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv))
